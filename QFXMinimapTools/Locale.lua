local locales = { enUS = L_EN, zhCN = L_ZH, zhTW = L_ZH_TW }
local L = locales[LOCALE] or L_EN
QMT.TITLE = TITLE
QMT.CLIENT_LOCALE = CLIENT_LOCALE
QMT.LOCALE = LOCALE
QMT.ZH = ZH
QMT.L_ZH = L_ZH
QMT.L_EN = L_EN
QMT.L = L

local function SelectLocale(choice)
    if choice == "ZH" then choice = "zhCN" end
    if choice == "EN" or choice == "enGB" then choice = "enUS" end
    if not locales[choice] then choice = CLIENT_LOCALE end
    LOCALE = locales[choice] and choice or "enUS"
    L = locales[LOCALE]
    ZH = LOCALE ~= "enUS"
    QMT.LOCALE = LOCALE
    QMT.ZH = ZH
    QMT.L = L
end

local function NormalizeLanguageChoice(choice)
    if choice == "zhTW" then return "zhTW" end
    if choice == "zhCN" or choice == "ZH" then return "zhCN" end
    if choice == "enUS" or choice == "enGB" or choice == "EN" then return "enUS" end
    return "AUTO"
end

QMT.SelectLocale = SelectLocale
QMT.NormalizeLanguageChoice = NormalizeLanguageChoice
